                        </span>

                        <h2>Governing Law</h2>
                    </div>

                    <p>
                        Trademarks in Nepal are governed by the Patent, Design
                        and Trademark Act, 2022 (2079), and administered by the
                        Department of Industry (DOI), Ministry of Industry,
                        Commerce and Supplies. This is the sole authority for
                        examining, publishing, and registering trademarks in
                        the country.
                    </p>

                </div>
            </div>

            <!-- Who Can Apply -->
            <div class="col-lg-7">
                <div class="legal-info-card h-100">

                    <div class="legal-info-heading">
                        <span class="legal-info-icon">
                            <i class="bi bi-person-check"></i>
                        </span>

                        <h2>Who Can Apply</h2>
                    </div>

                    <p>
                        Any individual or business entity — Nepali or foreign —
                        can apply for trademark registration in Nepal. Foreign
                        applicants, including Indian businesses, must file
                        through a locally licensed Nepali trademark agent,
                        since the DOI does not accept direct applications from
                        entities without a presence in Nepal. This is where
                        Blue Inkk’s network becomes valuable — we coordinate
                        the entire filing through our local associates so you
                        don’t have to manage cross-border paperwork yourself.
                    </p>

                    <div class="legal-info-note">
                        <span class="legal-note-icon">
                            <i class="bi bi-info-lg"></i>
                        </span>

                        <p>
                            An important limitation to plan around: Nepal does
                            not allow multi-class applications. Each class of
                            goods or services requires its own separate
                            application, so if your brand covers more than one
                            class, you will need to file — and eventually renew
                            — each one individually.
                        </p>
                    </div>

                </div>
            </div>

        </div>
