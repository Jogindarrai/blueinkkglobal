<section class="filing-process-section">
    <div class="container">

        <div class="filing-process-header">
            <span class="filing-process-icon">
                <i class="bi bi-list-check"></i>
            </span>

            <h2>Step-by-Step Filing Process</h2>
        </div>

        <div class="filing-process-timeline">

            <div class="filing-process-item">
                <div class="filing-step-number">1</div>

                <div class="filing-step-content">
                    <h3>Clearance search</h3>

                    <p>
                        A preliminary search is recommended to check for
                        identical or deceptively similar marks already on the
                        Nepali register.
                    </p>
                </div>
            </div>

            <div class="filing-process-item">
                <div class="filing-step-number">2</div>

                <div class="filing-step-content">
                    <h3>Filing the application</h3>

                    <p>
                        The application, along with the Power of Attorney and
                        supporting documents, is filed with the DOI for a
                        single class.
                    </p>
                </div>
            </div>

            <div class="filing-process-item">
                <div class="filing-step-number">3</div>

                <div class="filing-step-content">
                    <h3>Preliminary/formal examination</h3>

                    <p>
                        The DOI checks the application for completeness and
                        compliance with filing formalities. This stage
                        typically takes a few weeks.
                    </p>
                </div>
            </div>

            <div class="filing-process-item">
                <div class="filing-step-number">4</div>

                <div class="filing-step-content">
                    <h3>Substantive examination</h3>

                    <p>
                        The Registrar examines the mark on absolute and
                        relative grounds — distinctiveness, conflict with
                        existing marks, and compliance with public
                        policy/morality standards under the Act.
                    </p>
                </div>
            </div>

            <div class="filing-process-item">
                <div class="filing-step-number">5</div>

                <div class="filing-step-content">
                    <h3>Publication</h3>

                    <p>
                        Once cleared, the mark is published in the Industrial
                        Property Bulletin/Trademarks Journal, issued
                        periodically by the DOI.
                    </p>
                </div>
            </div>

            <div class="filing-process-item">
                <div class="filing-step-number">6</div>

                <div class="filing-step-content">
                    <h3>Opposition window</h3>

                    <p>
                        Any third party may oppose the application within
                        90 days of publication. If opposed, the applicant must
                        file a counterstatement (generally within 21 days of
                        notice) or the application is treated as abandoned.
                        Both sides then file evidence, and a hearing follows if
                        the matter isn’t resolved.
                    </p>
                </div>
            </div>

            <div class="filing-process-item">
                <div class="filing-step-number">7</div>

                <div class="filing-step-content">
                    <h3>Registration</h3>

                    <p>
                        If no opposition is filed, or if an opposition is
                        decided in the applicant’s favour, the DOI proceeds to
                        register the mark and issues a registration
                        certificate.
                    </p>
                </div>
            </div>

        </div>

    </div>
</section>


